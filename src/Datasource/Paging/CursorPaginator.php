namespace Cake\Datasource\Paging;

use BackedEnum;
use Cake\Chronos\ChronosDate;
use Cake\Core\Exception\CakeException;
use Cake\Database\TypeFactory;
use Cake\Datasource\EntityInterface;
use Cake\Datasource\QueryInterface;
use Cake\Datasource\RepositoryInterface;
use Cake\Datasource\ResultSetDecorator;
use Cake\Utility\Security;
use DateTimeInterface;
use JsonException;

/**
 * Keyset (cursor) based paginator.
 *
 * Instead of `LIMIT/OFFSET` this paginator filters on the values of the sort
 * fields of the last (or first) row of the current page. Performance doesn't
 * degrade on deep pages and rows are neither skipped nor repeated when records
 * are inserted or deleted between requests. Page numbers and total counts are
 * not available.
 *
 * The request parameter `cursor` contains an opaque token generated by this
 * paginator. Use `CursorPaginatedInterface::nextCursor()` and `prevCursor()`
 * (or `PaginatorHelper::next()` / `prev()`) to build links. Cursors are signed
 * with `Security::getSalt()`, so clients can't build or modify them and the
 * format stays an internal detail. Changing the salt invalidates existing cursors.
 *
 * The order is always made unique by appending the primary key (see the
 * `stableSort` option). Only plain field based orders are supported. Sort
 * fields must not contain `NULL` values, as databases don't agree on how to
 * order them.
 *
 * ```
 * $articles = $this->paginate($this->Articles, [
 *     'className' => 'Cursor',
 *     'order' => ['created' => 'desc'],
 * ]);
 * ```
 */
class CursorPaginator extends NumericPaginator
{
    /**
     * Cursor direction to fetch the rows after the cursor.
     *
     * @var string
     */
    public const NEXT = 'n';

    /**
     * Cursor direction to fetch the rows before the cursor.
     *
     * @var string
     */
    public const PREV = 'p';

    /**
     * Default pagination settings.
     *
     * See `NumericPaginator::$_defaultConfig` for the shared options. In addition:
     *
     * - `cursor` - The cursor to start from. Usually set from the request.
     * - `stableSort` - Defaults to `true` as keyset pagination requires a unique
     *   order. Setting it to `false` is not supported.
     *
     * @var array<string, mixed>
     */
    protected array $_defaultConfig = [
        'page' => 1,
        'limit' => 20,
        'maxLimit' => 100,
        'allowedParameters' => ['limit', 'sort', 'direction', 'cursor'],
        'sortableFields' => null,
        'finder' => 'all',
        'scope' => null,
        'stableSort' => true,
        'cursor' => null,
    ];

    /**
     * Paginate a repository or query using keyset pagination.
     *
     * @param mixed $target The repository or query to paginate.
     * @param array $params Request params
     * @param array $settings The settings/configuration used for pagination.
     * @return \Cake\Datasource\Paging\CursorPaginatedInterface<int, mixed>
     */
    public function paginate(
        mixed $target,
        array $params = [],
        array $settings = [],
    ): CursorPaginatedInterface {
        $query = null;
        if ($target instanceof QueryInterface) {
            // Keyset conditions are added to the query, don't modify the caller's instance.
            $query = clone $target;
            $target = $query->getRepository();
            if ($target === null) {
                throw new CakeException('No repository set for query.');
            }
        }

        assert(
            $target instanceof RepositoryInterface,
            'Pagination target must be an instance of `' . QueryInterface::class
                . '` or `' . RepositoryInterface::class . '`.',
        );

        $data = $this->extractData($target, $params, $settings);
        $data['options']['page'] = 1;
        $order = $this->normalizeOrder($data['options']['order']);
        $limit = $data['options']['limit'];

        $cursor = $this->decodeCursor($data['options']['cursor'] ?? null, $order);
        $backward = $cursor !== null && $cursor['direction'] === static::PREV;
        $queryOrder = $backward ? $this->invertOrder($order) : $order;

        $queryData = $data;
        unset($queryData['options']['page']);
        $queryData['options']['order'] = [];
        $queryData['options']['limit'] = $limit + 1;
        $query = $this->getQuery($target, $query, $queryData);
        $query->orderBy($queryOrder, true);

        if ($cursor !== null) {
            $types = $this->getFieldTypes($query, array_keys($order));
            $query->where(
                $this->buildConditions($queryOrder, $cursor['values'], $types),
                $types,
            );
        }

        /** @var list<mixed> $rows */
        $rows = $query->all()->toList();
        $hasMore = count($rows) > $limit;
        if ($hasMore) {
            $rows = array_slice($rows, 0, $limit);
        }
        if ($backward) {
            $rows = array_reverse($rows);
        }

        $hasNextPage = $backward || $hasMore;
        $hasPrevPage = $backward ? $hasMore : $cursor !== null;
        $nextCursor = null;
        $prevCursor = null;
        $this->pagingParams['alias'] = $data['alias'];
        if ($rows) {
            if ($hasNextPage) {
                $nextCursor = $this->encodeCursor($rows[count($rows) - 1], $order, static::NEXT);
            }
            if ($hasPrevPage) {
                $prevCursor = $this->encodeCursor($rows[0], $order, static::PREV);
            }
        }

        $this->pagingParams['count'] = count($rows);
        $this->pagingParams['totalCount'] = null;
        $pagingParams = $this->buildParams($data);
        $pagingParams['hasNextPage'] = $nextCursor !== null;
        $pagingParams['hasPrevPage'] = $prevCursor !== null;
        $pagingParams['cursor'] = $cursor !== null ? $data['options']['cursor'] : null;
        $pagingParams['nextCursor'] = $nextCursor;
        $pagingParams['prevCursor'] = $prevCursor;

        /** @var \Cake\Datasource\Paging\CursorPaginatedResultSet<int, mixed> $result */
        $result = new CursorPaginatedResultSet(new ResultSetDecorator($rows), $pagingParams);

        return $result;
    }

    /**
     * Ensure the stable sort tiebreaker is always added.
     *
     * @param \Cake\Datasource\RepositoryInterface $object Repository object.
     * @param array<string, mixed> $options The pagination options being used for this request.
     * @return array<string, mixed>
     */
    protected function addStableSort(RepositoryInterface $object, array $options): array
    {
        $options['stableSort'] = $options['stableSort'] ?: true;

        return parent::addStableSort($object, $options);
    }

    /**
     * Validate the order and normalize the directions.
     *
     * @param mixed $order The order from the pagination options.
     * @return array<string, string>
     */
    protected function normalizeOrder(mixed $order): array
    {
        $normalized = [];
        foreach ((array)$order as $field => $direction) {
            $direction = is_string($direction) ? strtolower($direction) : null;
            if (!is_string($field) || !in_array($direction, [SortField::ASC, SortField::DESC], true)) {
                throw new CakeException(
                    'Cursor pagination only supports orders that map field names to `asc` or `desc`.',
                );
            }
            $normalized[$field] = $direction;
        }
        if ($normalized === []) {
            throw new CakeException(
                'Cursor pagination requires an order. Set the `order` option or enable `stableSort`.',
            );
        }

        return $normalized;
    }

    /**
     * Invert all directions of an order.
     *
     * @param array<string, string> $order Order to invert.
     * @return array<string, string>
     */
    protected function invertOrder(array $order): array
    {
        return array_map(
            fn(string $direction): string => $direction === SortField::ASC ? SortField::DESC : SortField::ASC,
            $order,
        );
    }

    /**
     * Build the keyset conditions selecting the rows after the cursor values.
     *
     * For an order of `a ASC, b DESC` this generates `a > :a OR (a = :a AND b < :b)`.
     *
     * @param array<string, string> $order The order used by the query.
     * @param array $values The cursor values, in order.
     * @param array<string, string> $types Field types.
     * @return array
     */
    protected function buildConditions(array $order, array $values, array $types): array
    {
        $values = array_combine(array_keys($order), $values);
        foreach ($values as $field => $value) {
            if (isset($types[$field]) && $value !== null) {
                $values[$field] = TypeFactory::build($types[$field])->marshal($value);
            }
        }

        $conditions = [];
        $equal = [];
        foreach ($order as $field => $direction) {
            $operator = $direction === SortField::ASC ? '>' : '<';
            $conditions[] = $equal + [$field . ' ' . $operator => $values[$field]];
            $equal[$field] = $values[$field];
        }

        return ['OR' => $conditions];
    }

    /**
     * Get the column types of the sort fields from the query type map.
     *
     * @param \Cake\Datasource\QueryInterface $query The query.
     * @param array<string> $fields Sort fields.
     * @return array<string, string>
     */
    protected function getFieldTypes(QueryInterface $query, array $fields): array
    {
        if (!method_exists($query, 'getTypeMap')) {
            return [];
        }

        $typeMap = $query->getTypeMap();
        $types = [];
        foreach ($fields as $field) {
            $type = $typeMap->type($field);
            if ($type !== null) {
                $types[$field] = $type;
            }
        }

        return $types;
    }

    /**
     * Encode a cursor for the given row.
     *
     * @param mixed $row Entity or array.
     * @param array<string, string> $order The order.
     * @param string $direction Either `CursorPaginator::NEXT` or `CursorPaginator::PREV`.
     * @return string
     */
    protected function encodeCursor(mixed $row, array $order, string $direction): string
    {
        $values = [];
        foreach (array_keys($order) as $field) {
            $values[] = $this->serializeValue($field, $this->extractValue($row, $field));
        }

        $json = json_encode(
            ['d' => $direction, 'k' => $this->orderKey($order), 'v' => $values],
            JSON_THROW_ON_ERROR | JSON_PRESERVE_ZERO_FRACTION,
        );

        $payload = $this->base64UrlEncode($json);

        return $payload . '.' . $this->base64UrlEncode($this->sign($payload));
    }

    /**
     * Calculate the signature of a cursor payload.
     *
     * @param string $payload The encoded cursor payload.
     * @return string Raw binary signature.
     */
    protected function sign(string $payload): string
    {
        return hash_hmac('sha256', static::class . '|' . $payload, Security::getSalt(), true);
    }

    /**
     * Encode a string using URL safe base64 without padding.
     *
     * @param string $value The value to encode.
     * @return string
     */
    protected function base64UrlEncode(string $value): string
    {
        return rtrim(strtr(base64_encode($value), '+/', '-_'), '=');
    }

    /**
     * Decode a URL safe base64 string.
     *
     * @param string $value The value to decode.
     * @return string|null Null if the value is not valid base64.
     */
    protected function base64UrlDecode(string $value): ?string
    {
        $decoded = base64_decode(strtr($value, '-_', '+/'), true);

        return $decoded === false ? null : $decoded;
    }

    /**
     * Decode a cursor.
     *
     * Invalid cursors, cursors with an invalid signature and cursors generated
     * for a different order are ignored.
     *
     * @param mixed $cursor The cursor from the request.
     * @param array<string, string> $order The current order.
     * @return array{direction: string, values: array}|null
     */
    protected function decodeCursor(mixed $cursor, array $order): ?array
    {
        if (!is_string($cursor) || $cursor === '') {
            return null;
        }

        $parts = explode('.', $cursor);
        if (count($parts) !== 2) {
            return null;
        }
        [$payload, $signature] = $parts;
        $signature = $this->base64UrlDecode($signature);
        if ($signature === null || !hash_equals($this->sign($payload), $signature)) {
            return null;
        }

        $json = $this->base64UrlDecode($payload);
        if ($json === null) {
            return null;
        }
        try {
            $data = json_decode($json, true, 4, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            return null;
        }

        if (
            !is_array($data)
            || !in_array($data['d'] ?? null, [static::NEXT, static::PREV], true)
            || ($data['k'] ?? null) !== $this->orderKey($order)
            || !is_array($data['v'] ?? null)
            || !array_is_list($data['v'])
            || count($data['v']) !== count($order)
        ) {
            return null;
        }
        foreach ($data['v'] as $value) {
            if (!is_scalar($value)) {
                return null;
            }
        }

        return ['direction' => $data['d'], 'values' => $data['v']];
    }

    /**
     * Get a short key identifying an order, so cursors of a different order are rejected.
     *
     * @param array<string, string> $order The order.
     * @return string
     */
    protected function orderKey(array $order): string
    {
        return hash('crc32b', (string)json_encode($order));
    }

    /**
     * Extract the value of a sort field from a row.
     *
     * @param mixed $row Entity or array.
     * @param string $field Field name, prefixed with the table alias.
     * @return mixed
     */
    protected function extractValue(mixed $row, string $field): mixed
    {
        $alias = $this->pagingParams['alias'] ?? null;
        $fieldAlias = null;
        $property = $field;
        if (str_contains($field, '.')) {
            [$fieldAlias, $property] = explode('.', $field, 2);
        }

        if ($fieldAlias !== null && $fieldAlias !== $alias) {
            $matching = $row instanceof EntityInterface
                ? $row->get('_matchingData')
                : ($row['_matchingData'] ?? null);
            $row = $matching[$fieldAlias] ?? null;
        }

        if ($row instanceof EntityInterface) {
            return $row->get($property);
        }
        if (is_array($row) && array_key_exists($property, $row)) {
            return $row[$property];
        }

        throw new CakeException(sprintf(
            'Cannot read the cursor value of `%s` from the paginated row. '
            . 'Cursor pagination only supports fields of the paginated table or matched associations.',
            $field,
        ));
    }

    /**
     * Convert a value into a JSON serializable scalar.
     *
     * @param string $field Field name.
     * @param mixed $value The value.
     * @return string|float|int|bool
     */
    protected function serializeValue(string $field, mixed $value): string|int|float|bool
    {
        if ($value instanceof DateTimeInterface) {
            return $value->format('Y-m-d\TH:i:s.uP');
        }
        if ($value instanceof ChronosDate) {
            return $value->format('Y-m-d');
        }
        if ($value instanceof BackedEnum) {
            return $value->value;
        }
        if (is_scalar($value)) {
            return $value;
        }
        if ($value === null) {
            throw new CakeException(sprintf(
                'Cursor pagination does not support `NULL` values in sort fields. Field `%s` is `NULL`.',
                $field,
            ));
        }

        throw new CakeException(sprintf(
            'Cannot use the value of field `%s` (`%s`) in a pagination cursor.',
            $field,
            get_debug_type($value),
        ));
    }
}
